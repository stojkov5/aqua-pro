-- Aqua Pro shop schema: products, orders, order items.
-- Run once in Supabase → SQL Editor.

-- ---------------------------------------------------------------------------
-- Products (public, read-only for visitors)
-- ---------------------------------------------------------------------------
create table public.products (
  id          bigint generated by default as identity primary key,
  name        text not null,
  image       text not null,
  images      text[],
  price_eur   numeric(10, 2) not null check (price_eur >= 0),
  price_mkd   integer not null check (price_mkd >= 0),
  has_sizes   boolean not null default false,
  gender      text check (gender in ('male', 'female')),
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Orders (private: only the server and the dashboard can see them)
-- ---------------------------------------------------------------------------
create table public.orders (
  id              uuid primary key default gen_random_uuid(),
  order_number    bigint generated always as identity (start with 1001) unique,
  customer_name   text not null,
  customer_email  text not null,
  customer_phone  text not null,
  total_eur       numeric(10, 2) not null default 0,
  status          text not null default 'new'
                  check (status in ('new', 'confirmed', 'paid', 'completed', 'cancelled')),
  notes           text,
  created_at      timestamptz not null default now()
);

create table public.order_items (
  id              bigint generated always as identity primary key,
  order_id        uuid not null references public.orders (id) on delete cascade,
  product_id      bigint references public.products (id) on delete set null,
  product_name    text not null,
  size            text,
  quantity        integer not null check (quantity between 1 and 20),
  unit_price_eur  numeric(10, 2) not null,
  subtotal_eur    numeric(10, 2) generated always as (unit_price_eur * quantity) stored
);

create index order_items_order_id_idx on public.order_items (order_id);
create index orders_created_at_idx on public.orders (created_at desc);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.products    enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

create policy "Visitors can read active products"
  on public.products for select
  to anon, authenticated
  using (is_active);

-- No policies on orders / order_items: visitors cannot read or write them.
-- The server uses the secret key, which bypasses RLS.

grant select on public.products to anon, authenticated;
revoke all on public.orders, public.order_items from anon, authenticated;

-- ---------------------------------------------------------------------------
-- create_order: saves an order and its items in one transaction.
-- Prices always come from the products table, never from the browser.
-- p_items: [{ "id": 1, "size": "M", "quantity": 2 }, ...]
-- ---------------------------------------------------------------------------
create or replace function public.create_order(
  p_customer_name  text,
  p_customer_email text,
  p_customer_phone text,
  p_items          jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order_id     uuid;
  v_order_number bigint;
  v_item         jsonb;
  v_product      public.products;
  v_quantity     integer;
  v_size         text;
  v_total        numeric(10, 2) := 0;
begin
  if jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 30 then
    raise exception 'invalid_items';
  end if;

  insert into public.orders (customer_name, customer_email, customer_phone)
  values (p_customer_name, p_customer_email, p_customer_phone)
  returning id, order_number into v_order_id, v_order_number;

  for v_item in select * from jsonb_array_elements(p_items) loop
    select * into v_product
    from public.products
    where id = (v_item ->> 'id')::bigint and is_active;

    if not found then
      raise exception 'invalid_items';
    end if;

    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity is null or v_quantity < 1 or v_quantity > 20 then
      raise exception 'invalid_items';
    end if;

    v_size := nullif(left(trim(v_item ->> 'size'), 60), '');
    if v_product.has_sizes and v_size is null then
      raise exception 'invalid_items';
    end if;
    if not v_product.has_sizes then
      v_size := null;
    end if;

    insert into public.order_items (order_id, product_id, product_name, size, quantity, unit_price_eur)
    values (v_order_id, v_product.id, v_product.name, v_size, v_quantity, v_product.price_eur);

    v_total := v_total + v_product.price_eur * v_quantity;
  end loop;

  update public.orders set total_eur = v_total where id = v_order_id;

  return jsonb_build_object(
    'orderId', v_order_id,
    'orderNumber', v_order_number,
    'total', v_total,
    'items', (
      select jsonb_agg(
               jsonb_build_object(
                 'name', oi.product_name,
                 'size', oi.size,
                 'quantity', oi.quantity,
                 'unitPrice', oi.unit_price_eur,
                 'subtotal', oi.subtotal_eur
               ) order by oi.id)
      from public.order_items oi
      where oi.order_id = v_order_id
    )
  );
end;
$$;

-- Only the server (secret / service_role key) may create orders.
revoke execute on function public.create_order(text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.create_order(text, text, text, jsonb) to service_role;
